#requires -Version 7.0
param([Parameter(Mandatory=$true)][string]$BackupDirectory)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$backup = (Resolve-Path -LiteralPath $BackupDirectory).Path
$manifest = Get-Content -LiteralPath (Join-Path $backup 'manifest.json') -Raw | ConvertFrom-Json
if ($manifest.version -ne 1 -or -not $manifest.writesPaused -or $null -eq $manifest.rowCounts) { throw 'Unsupported or incomplete backup' }
$dump = Join-Path $backup 'database.sql'
if ((Get-FileHash -LiteralPath $dump -Algorithm SHA256).Hash -ne $manifest.databaseSha256) { throw 'Database checksum mismatch; restore refused' }
$uploadsRoot = [IO.Path]::GetFullPath((Join-Path $backup 'uploads')) + [IO.Path]::DirectorySeparatorChar
foreach ($file in $manifest.uploads) {
    $path = [IO.Path]::GetFullPath((Join-Path $uploadsRoot $file.path))
    if (-not $path.StartsWith($uploadsRoot,[StringComparison]::OrdinalIgnoreCase)) { throw 'Unsafe upload path in manifest' }
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $file.sha256) { throw 'Upload checksum mismatch; restore refused' }
}
$uri = [Uri]($env:UNINEST_DB_URL -replace '^jdbc:', '')
$mysql = 'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
$argsMysql = @("--host=$($uri.Host)","--port=$($uri.Port)","--user=$env:UNINEST_DB_USER",'--default-character-set=utf8mb4','--batch','--skip-column-names')
$testName = 'uninest_restore_check_' + [Guid]::NewGuid().ToString('N').Substring(0,12)
$oldPassword = $env:MYSQL_PWD
try {
    $env:MYSQL_PWD = $env:UNINEST_DB_PASSWORD
    & $mysql @argsMysql --execute="CREATE DATABASE $testName CHARACTER SET utf8mb4"
    if ($LASTEXITCODE -ne 0) { throw 'Could not create disposable restore database' }
    # Import only backups generated by backup-uninest.ps1; SQL is executable, not passive data.
    $start = [Diagnostics.ProcessStartInfo]::new($mysql)
    $start.UseShellExecute = $false
    $start.CreateNoWindow = $true
    $start.RedirectStandardInput = $true
    $start.RedirectStandardOutput = $true
    $start.RedirectStandardError = $true
    foreach ($argument in $argsMysql) { $start.ArgumentList.Add($argument) }
    $start.ArgumentList.Add("--database=$testName")
    $process = [Diagnostics.Process]::new()
    $process.StartInfo = $start
    try {
        [void]$process.Start()
        $output = $process.StandardOutput.ReadToEndAsync()
        $errors = $process.StandardError.ReadToEndAsync()
        $inputFile = [IO.File]::OpenRead($dump)
        try { $inputFile.CopyTo($process.StandardInput.BaseStream) }
        finally { $inputFile.Dispose(); $process.StandardInput.Close() }
        $process.WaitForExit()
        [void]$output.GetAwaiter().GetResult()
        [void]$errors.GetAwaiter().GetResult()
        if ($process.ExitCode -ne 0) { throw "Restore failed in $testName; disposable database retained for diagnosis" }
    } finally { $process.Dispose() }
    $tables = @(& $mysql @argsMysql "--database=$testName" --execute='SHOW TABLES')
    if ($LASTEXITCODE -ne 0 -or $tables.Count -eq 0) { throw 'Restore has no readable tables' }
    if ($tables.Count -ne @($manifest.rowCounts.PSObject.Properties).Count) { throw 'Restored table count differs' }
    foreach ($table in $tables) {
        if ($table -notmatch '^[A-Za-z0-9_]+$') { throw 'Unexpected table name' }
        $count = & $mysql @argsMysql "--database=$testName" "--execute=SELECT COUNT(*) FROM ``$table``"
        if ($LASTEXITCODE -ne 0) { throw "Restored table cannot be read: $table" }
        if ($null -eq $manifest.rowCounts.$table -or [long]$count -ne [long]$manifest.rowCounts.$table) { throw "Restored row count differs: $table" }
    }
    $restored = Join-Path $root ('test-runtime\restore-checks\' + $testName)
    foreach ($file in $manifest.uploads) {
        $target = Join-Path $restored $file.path
        New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force | Out-Null
        Copy-Item -LiteralPath (Join-Path $uploadsRoot $file.path) -Destination $target
        if ((Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash -ne $file.sha256) { throw 'Restored upload differs from backup' }
    }
    Write-Output "PASS: restored $($tables.Count) readable tables and $(@($manifest.uploads).Count) verified files."
    Write-Output "Disposable database retained: $testName"
    Write-Output "Restored uploads: $restored"
} finally { $env:MYSQL_PWD = $oldPassword }
